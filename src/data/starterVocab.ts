function makeCard(
  id: string,
  deckId: string,
  language: 'en' | 'jp',
  front: string,
  back: string,
  extra: Partial<VocabCard> = {}
): VocabCard {
  return {
    id,
    deckId,
    language,
    front,
    back,
    due: Date.now(),
    stability: 0,
    difficulty: 0,
    elapsedDays: 0,
    scheduledDays: 0,
    reps: 0,
    lapses: 0,
    state: 0,
    createdAt: BASE_TIME,
    updatedAt: BASE_TIME,
    ...extra,
  };
}

